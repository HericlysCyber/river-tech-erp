CREATE OR REPLACE FUNCTION public.erp_registrar_historico_preco()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.preco_normal IS DISTINCT FROM OLD.preco_normal THEN
    INSERT INTO public.erp_historico_precos (empresa_id, produto_id, preco_anterior, preco_novo, origem, data_hora, alterado_por)
    VALUES (NEW.empresa_id, NEW.produto_id, OLD.preco_normal, NEW.preco_normal,
      CASE WHEN current_setting('river.apply_price', true) = 'on' THEN 'AGENDAMENTO' ELSE 'PRECIFICACAO' END,
      now(), auth.uid());
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_erp_registrar_historico_preco ON public.erp_precos_base;
CREATE TRIGGER trg_erp_registrar_historico_preco
AFTER UPDATE OF preco_normal ON public.erp_precos_base
FOR EACH ROW EXECUTE FUNCTION public.erp_registrar_historico_preco();

-- Garante que produtos novos ou alterados diretamente no cadastro sincronizem o preço-base.
CREATE OR REPLACE FUNCTION public.erp_sync_preco_base_produto()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF current_setting('river.apply_price', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.erp_ofertas o
    WHERE o.empresa_id = NEW.empresa_id AND o.produto_id = NEW.id
      AND o.status <> 'CANCELADA' AND o.inicio_em <= now() AND o.fim_em > now()
      AND o.preco_oferta = NEW.preco_venda
  ) THEN
    RETURN NEW;
  END IF;
  INSERT INTO public.erp_precos_base (empresa_id, produto_id, preco_normal, updated_at)
  VALUES (NEW.empresa_id, NEW.id, COALESCE(NEW.preco_venda, 0), now())
  ON CONFLICT (empresa_id, produto_id)
  DO UPDATE SET preco_normal = EXCLUDED.preco_normal, updated_at = now();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_erp_sync_preco_base_produto ON public.erp_produtos;
CREATE TRIGGER trg_erp_sync_preco_base_produto
AFTER INSERT OR UPDATE OF preco_venda ON public.erp_produtos
FOR EACH ROW EXECUTE FUNCTION public.erp_sync_preco_base_produto();

-- Custo histórico em cada item vendido. Vendas anteriores à migração não podem ser reconstruídas com exatidão.
ALTER TABLE public.erp_venda_itens ADD COLUMN IF NOT EXISTS custo_unitario numeric(14,4);
CREATE OR REPLACE FUNCTION public.erp_capturar_custo_historico_venda()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE v_custo numeric(14,4);
BEGIN
  IF NEW.custo_unitario IS NULL AND NEW.produto_id IS NOT NULL THEN
    SELECT p.preco_custo INTO v_custo
    FROM public.erp_produtos p
    WHERE p.id = NEW.produto_id
      AND (NEW.empresa_id IS NULL OR p.empresa_id = NEW.empresa_id)
    LIMIT 1;
    IF v_custo IS NOT NULL THEN
      NEW.custo_unitario := v_custo;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_erp_capturar_custo_historico_venda ON public.erp_venda_itens;
CREATE TRIGGER trg_erp_capturar_custo_historico_venda
BEFORE INSERT ON public.erp_venda_itens
FOR EACH ROW EXECUTE FUNCTION public.erp_capturar_custo_historico_venda();

-- Função central: aplica preços agendados vencidos e, em seguida, recalcula os preços
-- efetivos de todos os produtos conforme a oferta vigente. A função é idempotente.
CREATE OR REPLACE FUNCTION public.erp_aplicar_precos_agendados()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_item record;
  v_total integer := 0;
BEGIN
  PERFORM set_config('river.apply_price', 'on', true);

  FOR v_item IN
    SELECT id, empresa_id, produto_id, preco_novo
    FROM public.erp_precos_agendados
    WHERE status = 'AGENDADO' AND data_hora_efetiva <= now()
    ORDER BY data_hora_efetiva, id
    FOR UPDATE
  LOOP
    INSERT INTO public.erp_precos_base (empresa_id, produto_id, preco_normal, updated_at)
    VALUES (v_item.empresa_id, v_item.produto_id, v_item.preco_novo, now())
    ON CONFLICT (empresa_id, produto_id)
    DO UPDATE SET preco_normal = EXCLUDED.preco_normal, updated_at = now();

    UPDATE public.erp_precos_agendados
    SET status = 'APLICADO', aplicado_em = now()
    WHERE id = v_item.id;
    v_total := v_total + 1;
  END LOOP;

  UPDATE public.erp_ofertas
  SET status = 'ENCERRADA', updated_at = now()
  WHERE status <> 'CANCELADA' AND fim_em <= now() AND status <> 'ENCERRADA';

  UPDATE public.erp_ofertas
  SET status = 'ATIVA', updated_at = now()
  WHERE status = 'AGENDADA' AND inicio_em <= now() AND fim_em > now();

  UPDATE public.erp_produtos p
  SET preco_venda = COALESCE(
    (SELECT o.preco_oferta
     FROM public.erp_ofertas o
     WHERE o.empresa_id = p.empresa_id
       AND o.produto_id = p.id
       AND o.status = 'ATIVA'
       AND o.inicio_em <= now()
       AND o.fim_em > now()
     ORDER BY o.inicio_em DESC, o.id DESC
     LIMIT 1),
    b.preco_normal,
    p.preco_venda
  )
  FROM public.erp_precos_base b
  WHERE b.empresa_id = p.empresa_id AND b.produto_id = p.id
    AND p.preco_venda IS DISTINCT FROM COALESCE(
      (SELECT o.preco_oferta
       FROM public.erp_ofertas o
       WHERE o.empresa_id = p.empresa_id
         AND o.produto_id = p.id
         AND o.status = 'ATIVA'
         AND o.inicio_em <= now()
         AND o.fim_em > now()
       ORDER BY o.inicio_em DESC, o.id DESC
       LIMIT 1),
      b.preco_normal,
      p.preco_venda
    );

  RETURN v_total;
END;
$$;

