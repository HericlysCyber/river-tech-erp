-- Helpers de contexto: retornam a empresa/tipo do usuário autenticado.
CREATE OR REPLACE FUNCTION public.erp_empresa_usuario_atual_text()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT u.empresa_id::text
  FROM public.erp_usuarios u
  WHERE u.auth_user_id = auth.uid()
    AND COALESCE(u.ativo, false) = true
    AND COALESCE(u.bloqueado, false) = false
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.erp_tipo_usuario_atual_text()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT upper(trim(COALESCE(u.tipo, '')))
  FROM public.erp_usuarios u
  WHERE u.auth_user_id = auth.uid()
    AND COALESCE(u.ativo, false) = true
    AND COALESCE(u.bloqueado, false) = false
  LIMIT 1;
$$;

-- Cria tabelas com tipos de empresa/produto/venda compatíveis com os IDs reais do projeto.
DO $$
DECLARE
  v_empresa_type text;
  v_produto_type text;
  v_venda_type text;
  v_cliente_type text;
  v_cliente_id_def text;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod) INTO v_empresa_type
  FROM pg_attribute a WHERE a.attrelid = 'public.erp_empresas'::regclass AND a.attname = 'id' AND NOT a.attisdropped;
  SELECT format_type(a.atttypid, a.atttypmod) INTO v_produto_type
  FROM pg_attribute a WHERE a.attrelid = 'public.erp_produtos'::regclass AND a.attname = 'id' AND NOT a.attisdropped;
  SELECT format_type(a.atttypid, a.atttypmod) INTO v_venda_type
  FROM pg_attribute a WHERE a.attrelid = 'public.erp_vendas'::regclass AND a.attname = 'id' AND NOT a.attisdropped;
  IF v_empresa_type IS NULL OR v_produto_type IS NULL OR v_venda_type IS NULL THEN
    RAISE EXCEPTION 'Não encontrei as tabelas-base erp_empresas, erp_produtos e erp_vendas. Confira se está no projeto Supabase correto.';
  END IF;

  -- Se o vínculo de venda já existir, aproveita o tipo de ID de cliente usado nele.
  IF to_regclass('public.erp_clientes') IS NULL THEN
    SELECT format_type(a.atttypid, a.atttypmod) INTO v_cliente_type
    FROM pg_attribute a
    WHERE a.attrelid = to_regclass('public.erp_venda_clientes')
      AND a.attname = 'cliente_id' AND NOT a.attisdropped;
    IF v_cliente_type = 'uuid' THEN
      v_cliente_id_def := 'uuid DEFAULT gen_random_uuid() PRIMARY KEY';
    ELSIF v_cliente_type IN ('smallint','integer','bigint') THEN
      v_cliente_id_def := v_cliente_type || ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    ELSE
      v_cliente_type := 'bigint';
      v_cliente_id_def := 'bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    END IF;
  ELSE
    v_cliente_id_def := NULL;
  END IF;

  -- Cadastro de clientes por loja.
  IF v_cliente_id_def IS NULL THEN
    EXECUTE format($q$
      CREATE TABLE IF NOT EXISTS public.erp_clientes (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        empresa_id %s NOT NULL,
      nome text NOT NULL,
      cpf text NOT NULL,
      data_nascimento date,
      telefone text,
      logradouro text,
      numero text,
      complemento text,
      bairro text,
      cidade text,
      uf varchar(2),
      cep text,
      observacoes text,
      ativo boolean NOT NULL DEFAULT true,
      created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      )$q$, v_empresa_type);
  ELSE
    EXECUTE format($q$
      CREATE TABLE IF NOT EXISTS public.erp_clientes (
        id %s,
        empresa_id %s NOT NULL,
        nome text NOT NULL,
        cpf text NOT NULL,
        data_nascimento date,
        telefone text,
        logradouro text,
        numero text,
        complemento text,
        bairro text,
        cidade text,
        uf varchar(2),
        cep text,
        observacoes text,
        ativo boolean NOT NULL DEFAULT true,
        created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      )$q$, v_cliente_id_def, v_empresa_type);
  END IF;

  -- Complementa instalações em que a tabela de clientes já existia.
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS nome text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS cpf text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS data_nascimento date;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS telefone text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS logradouro text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS numero text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS complemento text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS bairro text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS cidade text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS uf varchar(2);
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS cep text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS observacoes text;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS ativo boolean NOT NULL DEFAULT true;
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
  ALTER TABLE public.erp_clientes ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

  -- Tipos de cliente e venda acompanham os tipos de ID existentes.
  SELECT format_type(a.atttypid, a.atttypmod) INTO v_cliente_type
  FROM pg_attribute a WHERE a.attrelid = 'public.erp_clientes'::regclass AND a.attname = 'id' AND NOT a.attisdropped;
  EXECUTE format($q$
    CREATE TABLE IF NOT EXISTS public.erp_venda_clientes (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      empresa_id %s NOT NULL,
      venda_id %s NOT NULL,
      cliente_id %s NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now()
    )$q$, v_empresa_type, v_venda_type, v_cliente_type);

  -- Tabela de preço normal, separada do preço promocional aplicado ao PDV.
  EXECUTE format($q$
    CREATE TABLE IF NOT EXISTS public.erp_precos_base (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      empresa_id %s NOT NULL,
      produto_id %s NOT NULL,
      preco_normal numeric(14,2) NOT NULL DEFAULT 0 CHECK (preco_normal >= 0),
      updated_at timestamptz NOT NULL DEFAULT now(),
      UNIQUE (empresa_id, produto_id)
    )$q$, v_empresa_type, v_produto_type);

  EXECUTE format($q$
    CREATE TABLE IF NOT EXISTS public.erp_precos_agendados (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      empresa_id %s NOT NULL,
      produto_id %s NOT NULL,
      preco_anterior numeric(14,2),
      preco_novo numeric(14,2) NOT NULL CHECK (preco_novo >= 0),
      data_hora_efetiva timestamptz NOT NULL,
      status text NOT NULL DEFAULT 'AGENDADO' CHECK (status IN ('AGENDADO','APLICADO','CANCELADO')),
      aplicado_em timestamptz,
      criado_por uuid,
      created_at timestamptz NOT NULL DEFAULT now()
    )$q$, v_empresa_type, v_produto_type);

  EXECUTE format($q$
    CREATE TABLE IF NOT EXISTS public.erp_ofertas (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      empresa_id %s NOT NULL,
      produto_id %s NOT NULL,
      preco_normal numeric(14,2) NOT NULL CHECK (preco_normal >= 0),
      preco_oferta numeric(14,2) NOT NULL CHECK (preco_oferta > 0 AND preco_oferta < preco_normal),
      inicio_em timestamptz NOT NULL,
      fim_em timestamptz NOT NULL,
      observacoes text,
      status text NOT NULL DEFAULT 'AGENDADA' CHECK (status IN ('AGENDADA','ATIVA','ENCERRADA','CANCELADA')),
      criado_por uuid,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now(),
      CHECK (fim_em > inicio_em)
    )$q$, v_empresa_type, v_produto_type);

  EXECUTE format($q$
    CREATE TABLE IF NOT EXISTS public.erp_historico_precos (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      empresa_id %s NOT NULL,
      produto_id %s NOT NULL,
      preco_anterior numeric(14,2),
      preco_novo numeric(14,2) NOT NULL,
      origem text NOT NULL DEFAULT 'PRECIFICACAO',
      data_hora timestamptz NOT NULL DEFAULT now(),
      alterado_por uuid,
      created_at timestamptz NOT NULL DEFAULT now()
    )$q$, v_empresa_type, v_produto_type);
END $$;

-- Índices de busca e proteção contra duplicidade de CPF por loja.
CREATE INDEX IF NOT EXISTS idx_erp_clientes_empresa_nome ON public.erp_clientes (empresa_id, nome);
CREATE INDEX IF NOT EXISTS idx_erp_clientes_empresa_cpf ON public.erp_clientes (empresa_id, cpf);
CREATE INDEX IF NOT EXISTS idx_erp_venda_clientes_empresa_venda ON public.erp_venda_clientes (empresa_id, venda_id);
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.erp_venda_clientes
    GROUP BY empresa_id, venda_id HAVING count(*) > 1
  ) THEN
    CREATE UNIQUE INDEX IF NOT EXISTS idx_erp_venda_clientes_empresa_venda_unique
      ON public.erp_venda_clientes (empresa_id, venda_id);
  ELSE
    RAISE NOTICE 'Há vendas com mais de um vínculo em erp_venda_clientes; o índice único foi ignorado. Revise esses vínculos antes de usar o upsert do cliente no PDV.';
  END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS idx_erp_precos_base_empresa_produto ON public.erp_precos_base (empresa_id, produto_id);
CREATE INDEX IF NOT EXISTS idx_erp_precos_agendados_vigencia ON public.erp_precos_agendados (status, data_hora_efetiva);
