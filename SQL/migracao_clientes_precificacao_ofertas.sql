-- Normaliza CPFs já existentes e cria índice único apenas se não houver duplicados legados.
UPDATE public.erp_clientes SET cpf = regexp_replace(COALESCE(cpf, ''), '[^0-9]', '', 'g') WHERE cpf IS NOT NULL;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.erp_clientes
    WHERE cpf IS NOT NULL AND cpf <> ''
    GROUP BY empresa_id, cpf HAVING count(*) > 1
  ) THEN
    CREATE UNIQUE INDEX IF NOT EXISTS idx_erp_clientes_empresa_cpf_unique
      ON public.erp_clientes (empresa_id, cpf) WHERE cpf IS NOT NULL AND cpf <> '';
  ELSE
    RAISE NOTICE 'Há CPFs duplicados em erp_clientes; o índice único não foi criado. Revise os duplicados antes de tentar criar o índice novamente.';
  END IF;
END $$;

