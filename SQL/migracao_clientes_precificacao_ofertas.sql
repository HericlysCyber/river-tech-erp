DO $$
DECLARE v_seq text;
BEGIN
  FOR v_seq IN
    SELECT pg_get_serial_sequence(t, 'id')
    FROM unnest(ARRAY['public.erp_clientes','public.erp_venda_clientes','public.erp_precos_base','public.erp_precos_agendados','public.erp_ofertas','public.erp_historico_precos']) AS t
    WHERE pg_get_serial_sequence(t, 'id') IS NOT NULL
  LOOP
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', v_seq);
  END LOOP;
END $$;
